async function seedBulkCatalog() {
  console.log('--- Starting Bulk Seeding (15 items) ---');
  
  for (const item of catalogItems) {
    const { error } = await supabase
      .from('service_catalog')
      .upsert(item, { onConflict: 'slug' });

    if (error) {
      console.error(`Error seeding [${item.slug}]:`, error.message);
    } else {
      console.log(`Successfully seeded: ${item.slug}`);
    }
  }

  console.log('--- Seeding Completed! ---');
}

seedBulkCatalog();
