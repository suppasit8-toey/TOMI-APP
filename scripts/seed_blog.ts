async function seed() {
  console.log('Seeding blog posts...');
  for (const post of posts) {
    const { error } = await supabase.from('blog_posts').upsert(post, { onConflict: 'slug' });
    if (error) {
      console.error(`Error inserting post ${post.title}:`, error);
    } else {
      console.log(`Successfully inserted/updated ${post.title}`);
    }
  }
  console.log('Done!');
}

